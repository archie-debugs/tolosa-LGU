def _find_document_by_qr_or_tracking(db: Session, qr_value: str):
    if not qr_value:
        return None
    qr_text = str(qr_value).strip()
    if not qr_text:
        return None
    normalized_tracking = _normalize_tracking_query(qr_text)
    candidate_value = qr_text
    query = db.query(models.Document)
    if normalized_tracking is not None:
        canonical_tracking = f"DOC-{int(normalized_tracking)}"
        query = query.filter(
            or_(
                models.Document.qr_code_value == candidate_value,
                models.Document.qr_code_value == canonical_tracking,
                models.Document.tracking_number == canonical_tracking,
                models.Document.tracking_number == qr_text.upper(),
            )
        )
    else:
        query = query.filter(
            or_(
                models.Document.qr_code_value == candidate_value,
                models.Document.qr_code_value == qr_text.upper(),
                models.Document.tracking_number == qr_text.upper(),
            )
        )
    return query.first()


def _compute_qr_payload(doc: models.Document) -> str:
    backend_url = os.getenv("BACKEND_URL") or os.getenv("PUBLIC_BACKEND_URL") or os.getenv("API_BASE_URL") or "http://127.0.0.1:8001"
    backend_url = backend_url.rstrip("/")
    tracking = (doc.tracking_number or "").strip()
    if not tracking:
        tracking = f"DOC-{doc.id}"
    return f"{backend_url}/documents/qr/{quote(str(tracking), safe='')}"


def _qr_image_path_for_document(doc: models.Document) -> str:
    os.makedirs(QR_IMAGE_DIR, exist_ok=True)
    safe_tracking = (doc.tracking_number or f"DOC-{doc.id}").strip().replace(os.sep, "_").replace("/", "_")
    return os.path.join(QR_IMAGE_DIR, f"{safe_tracking}.png")


def _ensure_qr_png(doc: models.Document, payload: str | None = None) -> str:
    payload = payload or _compute_qr_payload(doc)
    image_path = _qr_image_path_for_document(doc)
    os.makedirs(QR_IMAGE_DIR, exist_ok=True)
    try:
        if not os.path.exists(image_path):
            qr_img = qrcode.make(payload)
            qr_img.save(image_path, format="PNG")
    except Exception:
        raise HTTPException(status_code=500, detail="Unable to generate the QR PNG image")
    return image_path


def _render_qr_label_pdf(documents: list[models.Document]):
    buffer = io.BytesIO()
    page_width, page_height = letter

    # The chosen QR label density is a compact, scan-friendly 4 x 6 page layout.
    # It prevents the QR from consuming too much page area while still leaving
    # enough room for the metadata below it.
    margin = 24
    columns = 4
    rows = 6

    label_width = (page_width - (margin * 2)) / columns
    label_height = (page_height - (margin * 2)) / rows

    # Keep the QR code in a forgiving size range for standard printer output.
    qr_side = min(52, label_width - 24, (label_height * 0.48))
    if qr_side < 40:
        qr_side = 40

    pdf = canvas.Canvas(buffer, pagesize=letter)

    for index, doc in enumerate(documents):
        if index > 0 and index % (columns * rows) == 0:
            pdf.showPage()

        local_index = index % (columns * rows)
        col = local_index % columns
        row_from_top = local_index // columns

        label_left = margin + col * label_width
        label_bottom = page_height - margin - (row_from_top + 1) * label_height

        qr_x = label_left + (label_width - qr_side) / 2
        qr_y = label_bottom + label_height - 24 - qr_side

        # Draw QR in the upper part of the label cell so the metadata is below it.
        value = doc.qr_code_value or doc.tracking_number or f"DOC-{doc.id}"
        qr_img = qrcode.make(str(value))
        qr_buffer = io.BytesIO()
        qr_img.save(qr_buffer, format="PNG")
        qr_buffer.seek(0)
        image = ImageReader(qr_buffer)

        pdf.drawImage(
            image,
            qr_x,
            qr_y,
            width=qr_side,
            height=qr_side,
            mask="auto",
        )

        text_y = label_bottom + 12
        pdf.setFont("Helvetica-Bold", 8)
        pdf.drawString(label_left + 8, text_y, f"{doc.tracking_number or 'No tracking'}")

        text_y += 13
        pdf.setFont("Helvetica", 7)
        title = (doc.title or "Untitled")[:38]
        pdf.drawString(label_left + 8, text_y, title)

        text_y += 12
        office = doc.current_office or "No location"
        pdf.drawString(label_left + 8, text_y, office)

    pdf.save()
    buffer.seek(0)
    return buffer


def _get_history_event_timestamp(item: dict):
    if item is None:
        return ""
    if item.get("created_at"):
        return str(item.get("created_at"))
    if item.get("date") and item.get("time"):
        return f"{item.get('date')} {item.get('time')}"
    if item.get("date"):
        return item.get("date")
    return ""


def _get_or_create_by_name(db: Session, Model, name: str):
    if not name:
        return None
    name = name.strip()
    existing = db.query(Model).filter(Model.name == name).first()
    if existing:
        return existing.id
    try:
        obj = Model(name=name)
        db.add(obj)
        db.commit()
        db.refresh(obj)
        return obj.id
    except exc.IntegrityError:
        db.rollback()
        existing = db.query(Model).filter(Model.name == name).first()
        return existing.id if existing else None


def _normalize_tracking_query(search: str | None) -> str | None:
    if search is None:
        return None
    text = str(search).strip()
    if not text:
        return None
    match = re.fullmatch(r"(?i)(?:doc[-\s]*)?0*([1-9][0-9]*|0)", text)
    if match:
        return match.group(1)
    return None


@router.get("", response_model=list[schemas.DocumentResponse])
def list_documents(
    search: str | None = Query(default=None),
    status: str | None = None,
    document_type: str | None = None,
    category: str | None = None,
    current_office: str | None = None,
    year: str | None = None,
    start_date: str | None = None,
    end_date: str | None = None,
    priority: str | None = None,
    archived: bool | None = Query(default=None),
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    require_permission(current_user, "view_documents")
    query = db.query(models.Document)
    if archived is not None:
        query = query.filter(models.Document.archived.is_(archived))
    else:
        query = query.filter(models.Document.archived.is_(False))
    if search:
        normalized_tracking = _normalize_tracking_query(search)
        if normalized_tracking is not None and re.fullmatch(r"(?i)(?:doc[-\s]*)?0*([1-9][0-9]*|0)", str(search).strip()):
            canonical_tracking = f"DOC-{int(normalized_tracking)}"
            query = query.filter(
                or_(
                    models.Document.tracking_number == canonical_tracking,
                    models.Document.tracking_number == str(search).strip().upper(),
                )
            )
        else:
            like = f"%{search.lower()}%"
            query = query.filter(
                or_(
                    models.Document.tracking_number.ilike(like),
                    models.Document.title.ilike(like),
                    models.Document.description.ilike(like),
                    models.Document.document_type.ilike(like),
                    models.Document.category.ilike(like),
                    models.Document.originating_office.ilike(like),
                    models.Document.current_office.ilike(like),
                    models.Document.assigned_to.ilike(like),
                    models.Document.status.ilike(like),
                    models.Document.remarks.ilike(like),
                    models.Document.author.ilike(like),
                    models.Document.session.ilike(like),
                    models.Document.created_by.ilike(like),
                )
            )
    if status:
        query = query.filter(models.Document.status == status)
    if document_type:
        query = query.filter(models.Document.document_type == document_type)
    if category:
        query = query.filter(models.Document.category == category)
    if current_office:
        query = query.filter(models.Document.current_office == current_office)
    if priority:
        query = query.filter(models.Document.priority == priority)
    if year:
        year_text = str(year).strip()
        if year_text.isdigit() and len(year_text) == 4:
            start_year = datetime(int(year_text), 1, 1, tzinfo=timezone.utc)
            end_year = datetime(int(year_text) + 1, 1, 1, tzinfo=timezone.utc)
            query = query.filter(models.Document.created_at >= start_year, models.Document.created_at < end_year)
    if start_date:
        query = query.filter(models.Document.created_at >= start_date)
    if end_date:
        query = query.filter(models.Document.created_at <= end_date)

    docs = query.order_by(models.Document.created_at.desc()).all()
    return [_serialize_document(doc) for doc in docs]




