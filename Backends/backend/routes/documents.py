def _extract_qr_token_from_value(qr_value: str | None) -> str | None:
    if qr_value is None:
        return None
    candidate = str(qr_value).strip()
    if not candidate:
        return None
    if "://" in candidate:
        parsed = urlparse(candidate)
        path = parsed.path or ""
        marker = path.lower().find("/qr/")
        if marker >= 0:
            # Slice the original path: QR tokens are case-sensitive.
            candidate = path[marker + len("/qr/"):]
        else:
            candidate = path.rsplit("/", 1)[-1]
    if candidate.startswith("/"):
        candidate = candidate.lstrip("/")
    candidate = unquote(candidate).strip().strip("/")
    if not candidate:
        return None
    return candidate


def _find_document_by_qr_or_tracking(db: Session, qr_value: str):
    if not qr_value:
        return None
    qr_text = str(qr_value).strip()
    if not qr_text:
        return None
    normalized_value = qr_text.upper()

    token_value = _extract_qr_token_from_value(qr_text)
    if token_value:
        token_match = db.query(models.Document).filter(models.Document.qr_token == token_value).first()
        if token_match is not None:
            return token_match

    current = db.query(models.Document).filter(models.Document.tracking_number == normalized_value).first()
    if current is not None:
        return current

    current_qr = db.query(models.Document).filter(models.Document.qr_code_value == qr_text).first()
    if current_qr is not None:
        return current_qr

    aliases = {normalized_value}
    normalized_tracking = _normalize_tracking_query(qr_text)
    if normalized_tracking is not None:
        numeric_tracking = int(normalized_tracking)
        aliases.add(f"DOC-{numeric_tracking}")
        aliases.add(f"DOC-{numeric_tracking:06d}")

    alias = (
        db.query(models.DocumentTrackingNumberAlias)
        .filter(models.DocumentTrackingNumberAlias.tracking_number.in_(aliases))
        .first()
    )
    if alias is None:
        return None
    return db.query(models.Document).filter(models.Document.id == alias.document_id).first()


