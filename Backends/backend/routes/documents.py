def _is_allowed_file(filename: str, content_type: str | None) -> tuple[bool, list[str]]:
    errors: list[str] = []
    if not filename:
        errors.append("Missing filename")
        return False, errors
    name = os.path.basename(filename)
    _, ext = os.path.splitext(name.lower())
    if ext not in ALLOWED_EXTENSIONS:
        errors.append("Unsupported file extension")
    if content_type and content_type not in ALLOWED_MIME_TYPES:
        # don't treat mime mismatch as fatal if extension is correct, but warn
        errors.append("Unexpected MIME type")
    return (len(errors) == 0), errors


@router.put("/uploads/tmp/{tmp_name}")
async def upload_tmp_file(tmp_name: str, request: Request, token: str | None = Query(default=None), upload_token: str | None = Query(default=None), db: Session = Depends(get_db)):
    """Accept raw PUT uploads from the browser FilePicker.upload() into TEMP_UPLOAD_DIR.
    The `tmp_name` should be a safe basename generated by the client.
    """
    # Authentication flows supported:
    # 1) Standard JWT in Authorization header -> identify user and require permission
    # 2) upload_token query parameter -> must match a server-created upload metadata file that ties the tmp_name to a specific user
    # 3) BACKEND_AUTH_TOKEN is retained only as an optional dev fallback (not recommended)
    auth_user = None
    env_token = os.getenv("BACKEND_AUTH_TOKEN")
    provided_token = token or request.query_params.get("token")
    provided_upload_token = upload_token or request.query_params.get("upload_token")

    # First, try upload_token path (pre-signed per-user upload)
    try:
        if provided_upload_token:
            # read metadata file for tmp_name
            safe_name = os.path.basename(tmp_name)
            meta_path = os.path.join(TEMP_UPLOAD_DIR, f"{safe_name}.meta.json")
            if not os.path.exists(meta_path):
                raise HTTPException(status_code=401, detail="Upload token invalid or expired")
            try:
                with open(meta_path, "r", encoding="utf-8") as mf:
                    meta = json.load(mf)
            except Exception:
                raise HTTPException(status_code=401, detail="Upload token invalid")
            # verify token and expiry
            if meta.get("upload_token") != provided_upload_token:
                raise HTTPException(status_code=401, detail="Upload token mismatch")
            expires_at = meta.get("expires_at", 0)
            if time.time() > expires_at:
                raise HTTPException(status_code=401, detail="Upload token expired")
            if meta.get("consumed_at"):
                raise HTTPException(status_code=401, detail="Upload token already used")
            # find the user by username stored in meta
            username = meta.get("username")
            if username:
                auth_user = db.query(models.User).filter(models.User.username == username).first()
            if not auth_user:
                raise HTTPException(status_code=401, detail="Upload token user not found")
            # enforce permission for resolved user
            require_permission(auth_user, "register_documents")
        else:
            # fallback to Authorization/JWT path
            auth_header = request.headers.get("authorization") or request.headers.get("Authorization")
            if provided_token:
                tok = provided_token
                if tok.lower().startswith("bearer "):
                    tok = tok.split(" ", 1)[1]
                payload = decode_access_token(tok)
                username = payload.get("sub")
                if username:
                    auth_user = db.query(models.User).filter(models.User.username == username).first()
            elif auth_header:
                tok = auth_header
                if tok.lower().startswith("bearer "):
                    tok = tok.split(" ", 1)[1]
                payload = decode_access_token(tok)
                username = payload.get("sub")
                if username:
                    auth_user = db.query(models.User).filter(models.User.username == username).first()
            # allow optional env token for dev fallback
            if not auth_user and env_token and provided_token == env_token:
                # dev fallback accepted but do not set auth_user
                pass
            else:
                if not auth_user:
                    raise HTTPException(status_code=401, detail="Not authenticated")
                require_permission(auth_user, "register_documents")
    except HTTPException:
        raise
    except Exception:
        raise HTTPException(status_code=401, detail="Not authenticated")
    try:
        safe_name = os.path.basename(tmp_name)
        if not safe_name:
            raise HTTPException(status_code=400, detail="Invalid upload name")
        # enforce allowed extension
        _, ext = os.path.splitext(safe_name.lower())
        if ext not in ALLOWED_EXTENSIONS:
            raise HTTPException(status_code=400, detail="Unsupported file extension")

        body = await request.body()
        size = len(body)
        if size == 0:
            raise HTTPException(status_code=400, detail="Empty upload")
        if size > MAX_FILE_SIZE:
            raise HTTPException(status_code=413, detail="File exceeds maximum allowed size")

        os.makedirs(TEMP_UPLOAD_DIR, exist_ok=True)
        dest_path = os.path.join(TEMP_UPLOAD_DIR, safe_name)
        with open(dest_path, "wb") as fh:
            fh.write(body)

        # if upload used upload_token flow, metadata file already exists; otherwise, create a simple meta file linking this tmp to the uploader for later validation/confirm
        meta_path = os.path.join(TEMP_UPLOAD_DIR, f"{safe_name}.meta.json")
        if not os.path.exists(meta_path):
            meta = {
                "tmp_name": safe_name,
                "original_filename": safe_name,
                "username": getattr(auth_user, "username", None),
                "upload_token": provided_upload_token or None,
                "created_at": int(time.time()),
                "expires_at": int(time.time()) + (10 * 60),
                "consumed_at": None,
                "consumed_by": None,
            }
            try:
                with open(meta_path, "w", encoding="utf-8") as mf:
                    json.dump(meta, mf)
            except Exception:
                pass
        elif provided_upload_token:
            try:
                with open(meta_path, "r", encoding="utf-8") as mf:
                    existing_meta = json.load(mf)
                existing_meta["consumed_at"] = int(time.time())
                existing_meta["consumed_by"] = getattr(auth_user, "username", None)
                existing_meta["upload_token"] = None
                with open(meta_path, "w", encoding="utf-8") as mf:
                    json.dump(existing_meta, mf)
            except Exception:
                pass

        return {"ok": True, "tmp_name": safe_name, "size": size}
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))


@router.post("/bulk-register/validate_tmp")
def validate_bulk_register_tmp(payload: dict = Body(...), db: Session = Depends(get_db), current_user: models.User = Depends(get_current_user)):
    """Validate temporary uploaded files by name (these files must exist in TEMP_UPLOAD_DIR)."""
    require_permission(current_user, "register_documents")
    tmp_names = payload.get("tmp_names") or []
    if not isinstance(tmp_names, list) or not tmp_names:
        raise HTTPException(status_code=400, detail="tmp_names list is required")

    results = []
    total = 0
    valid_count = 0
    invalid_count = 0
    for idx, tmp in enumerate(tmp_names, start=1):
        total += 1
        safe_name = os.path.basename(tmp or "")
        path = os.path.join(TEMP_UPLOAD_DIR, safe_name)
        errors = []
        if not os.path.exists(path):
            errors.append("Temporary file not found")
            invalid_count += 1
            results.append({"index": idx, "filename": safe_name, "valid": False, "errors": errors})
            continue
        try:
            size = os.path.getsize(path)
            if size == 0:
                errors.append("Empty file")
            if size > MAX_FILE_SIZE:
                errors.append("File exceeds maximum allowed size")
            _, ext = os.path.splitext(safe_name.lower())
            if ext not in ALLOWED_EXTENSIONS:
                errors.append("Unsupported file extension")

            if errors:
                invalid_count += 1
                results.append({"index": idx, "filename": safe_name, "valid": False, "errors": errors})
            else:
                valid_count += 1
                results.append({"index": idx, "filename": safe_name, "valid": True, "size": size, "tmp_name": safe_name})
        except Exception as exc:
            invalid_count += 1
            results.append({"index": idx, "filename": safe_name or f"file_{idx}", "valid": False, "errors": [str(exc)]})

    return {"total_files": total, "valid_files": valid_count, "invalid_files": invalid_count, "files": results}


@router.post("/uploads/create_tmp_uploads")
def create_tmp_uploads(payload: dict = Body(...), db: Session = Depends(get_db), current_user: models.User = Depends(get_current_user)):
    """Create server-side temporary upload entries and return per-file upload URLs with short-lived upload tokens.
    Payload: {"files": [{"filename": "...", "size": 123}, ...]}
    """
    require_permission(current_user, "register_documents")
    files = payload.get("files") or []
    if not isinstance(files, list) or not files:
        raise HTTPException(status_code=400, detail="files list required")

    os.makedirs(TEMP_UPLOAD_DIR, exist_ok=True)
    results = []
    for f in files:
        filename = f.get("filename") or ""
        safe_basename = os.path.basename(filename)
        _, ext = os.path.splitext(safe_basename.lower())
        if ext not in ALLOWED_EXTENSIONS:
            results.append({"filename": filename, "ok": False, "reason": "Unsupported extension"})
            continue
        # generate tmp name and upload token
        tmp_name = f"tmp_{int(time.time())}_{secrets.token_hex(8)}_{safe_basename}"
        upload_token = uuid.uuid4().hex
        expires_at = int(time.time()) + (10 * 60)  # 10 minutes
        meta = {
            "tmp_name": tmp_name,
            "original_filename": safe_basename,
            "username": getattr(current_user, "username", None),
            "upload_token": upload_token,
            "created_at": int(time.time()),
            "expires_at": expires_at,
            "consumed_at": None,
            "consumed_by": None,
        }
        meta_path = os.path.join(TEMP_UPLOAD_DIR, f"{tmp_name}.meta.json")
        try:
            with open(meta_path, "w", encoding="utf-8") as mf:
                json.dump(meta, mf)
        except Exception as exc:
            results.append({"filename": filename, "ok": False, "reason": f"meta write error: {exc}"})
            continue

        upload_url = f"/documents/uploads/tmp/{quote(tmp_name)}?upload_token={upload_token}"
        # return full absolute URL
        full_url = f"{os.getenv('BACKEND_URL', 'http://127.0.0.1:8001').rstrip('/')}" + upload_url
        results.append({"filename": filename, "ok": True, "tmp_name": tmp_name, "upload_url": full_url, "upload_token": upload_token})

    return {"files": results}


@router.post("/bulk-register/confirm_tmp")
def confirm_bulk_register_tmp(payload: dict = Body(...), db: Session = Depends(get_db), current_user: models.User = Depends(get_current_user)):
    """Confirm and create Document records from temporary uploaded files.
    Payload: {"tmp_names": [...], optional metadata fields }
    """
    require_permission(current_user, "register_documents")
    tmp_names = payload.get("tmp_names") or []
    if not isinstance(tmp_names, list) or not tmp_names:
        raise HTTPException(status_code=400, detail="tmp_names list is required")
    safe_tmp_names = [os.path.basename(tmp or "") for tmp in tmp_names]
    if any(not name for name in safe_tmp_names) or len(set(safe_tmp_names)) != len(safe_tmp_names):
        raise HTTPException(status_code=400, detail="Each uploaded document must have a unique temporary file name.")

    year_by_tmp_name = {}
    document_specs = payload.get("documents")
    if isinstance(document_specs, list):
        if len(document_specs) != len(safe_tmp_names):
            raise HTTPException(status_code=400, detail="Legislative Year is required for every document.")
        for spec in document_specs:
            if not isinstance(spec, dict):
                raise HTTPException(status_code=400, detail="Each document requires a Legislative Year.")
            safe_name = os.path.basename(spec.get("tmp_name") or "")
            if safe_name not in safe_tmp_names or safe_name in year_by_tmp_name:
                raise HTTPException(status_code=400, detail="Document year entries must match the uploaded files.")
            year_by_tmp_name[safe_name] = _parse_legislative_year(spec.get("series_year"))
    elif isinstance(payload.get("series_years"), list):
        years = payload["series_years"]
        if len(years) != len(safe_tmp_names):
            raise HTTPException(status_code=400, detail="Legislative Year is required for every document.")
        year_by_tmp_name = {
            name: _parse_legislative_year(year)
            for name, year in zip(safe_tmp_names, years)
        }
    elif payload.get("series_year") is not None:
        common_year = _parse_legislative_year(payload.get("series_year"))
        year_by_tmp_name = {name: common_year for name in safe_tmp_names}
    else:
        raise HTTPException(status_code=400, detail="Legislative Year is required for every document.")

    missing_years = [name for name in safe_tmp_names if year_by_tmp_name.get(name) is None]
    if missing_years:
        raise HTTPException(
            status_code=400,
            detail=f"A valid Legislative Year is required for: {', '.join(missing_years)}",
        )

    title = payload.get("title")
    description = payload.get("description")
    category = payload.get("category")
    document_type = payload.get("document_type")
    current_office = payload.get("current_office")
    assigned_to = payload.get("assigned_to")
    author = payload.get("author")
    priority = payload.get("priority") or "Medium"

    created = []
    failed = []
    duplicates = []

    _ensure_upload_dirs()

    for idx, tmp in enumerate(tmp_names, start=1):
        safe_name = os.path.basename(tmp or "")
        tmp_path = os.path.join(TEMP_UPLOAD_DIR, safe_name)
        if not os.path.exists(tmp_path):
            failed.append({"index": idx, "filename": safe_name, "reason": "Temporary file not found"})
            continue
        try:
            original_filename = safe_name
            meta_path = os.path.join(TEMP_UPLOAD_DIR, f"{safe_name}.meta.json")
            try:
                with open(meta_path, "r", encoding="utf-8") as mf:
                    original_filename = os.path.basename(json.load(mf).get("original_filename") or safe_name)
            except Exception:
                pass

            with open(tmp_path, "rb") as fh:
                content = fh.read()
            size = len(content)
            if size == 0:
                raise Exception("Empty file")
            if size > MAX_FILE_SIZE:
                raise Exception("File exceeds maximum allowed size")
            checksum = hashlib.sha256(content).hexdigest()
            duplicate_documents = _documents_with_checksum(db, checksum)
            if duplicate_documents:
                duplicates.append({"index": idx, "filename": original_filename, "checksum": checksum, "documents": [doc.tracking_number for doc in duplicate_documents]})
                failed.append({"index": idx, "filename": original_filename, "reason": _duplicate_reason(duplicate_documents), "duplicate": True, "checksum": checksum})
                continue

            base_title = os.path.splitext(original_filename)[0]
            doc_title = (title or base_title or f"Document {idx}").strip()
            inferred_number = _extract_legislative_number(original_filename or doc_title)
            document_number = (payload.get("document_number") or inferred_number or "").strip() or None
            series_year = year_by_tmp_name[safe_name]

            doc = models.Document(
                tracking_number=f"PENDING-{uuid.uuid4().hex}",
                document_number=document_number,
                series_year=series_year,
                title=doc_title,
                description=(description or None),
                category=(category or None),
                document_type=(document_type or None),
                current_office=(current_office or None),
                assigned_to=(assigned_to or None),
                author=(author or None),
                status="Approved",
                priority=(priority or "Medium") or "Medium",
                is_public=False,
                date_registered=datetime.now(timezone.utc).strftime("%Y-%m-%d"),
                qr_code_value=None,
                created_by=getattr(current_user, "username", None),
            )
            _assign_system_tracking_number(db, doc)
            db.commit()
            db.refresh(doc)
            qr_payload = _compute_qr_payload(doc)
            doc.qr_code_value = qr_payload
            db.commit()
            db.refresh(doc)
            _ensure_qr_png(doc, qr_payload)

            # move file from tmp to uploads
            safe_stored = f"{int(datetime.now(timezone.utc).timestamp())}_{secrets.token_hex(8)}_{os.path.basename(safe_name)}"
            dest_path = os.path.join(UPLOAD_DIR, safe_stored)
            with open(dest_path, "wb") as fh:
                fh.write(content)

            att = models.Attachment(
                document_id=doc.id,
                original_filename=original_filename,
                stored_path=dest_path,
                mime_type=mimetypes.guess_type(original_filename)[0],
                size=size,
                checksum=checksum,
            )
            db.add(att)
            doc.attachment_name = safe_stored
            if document_type:
                doc.document_type_id = _get_or_create_by_name(db, models.DocumentType, document_type)
            if current_office:
                doc.current_office_id = _get_or_create_by_name(db, models.Office, current_office)
                _ensure_document_office_association(db, doc.id, doc.current_office_id)

            db.commit()
            db.refresh(att)
            db.refresh(doc)

            created.append({"index": idx, "id": doc.id, "tracking_number": doc.tracking_number, "filename": original_filename})

            # remove tmp file
            try:
                os.remove(tmp_path)
            except Exception:
                pass
        except Exception as exc:
            try:
                db.rollback()
            except Exception:
                pass
            failed.append({"index": idx, "filename": safe_name or f"file_{idx}", "reason": str(exc)})

    # audit
    try:
        record_audit_log(
            db,
            actor=getattr(current_user, "username", None),
            action="BULK_DOCUMENT_REGISTRATION",
            target_type="Document",
            target_id=None,
            details=json.dumps({"submitted": len(tmp_names), "created": len(created), "failed": len(failed), "failures": failed}),
        )
    except Exception:
        pass

    return {"success": len(failed) == 0, "total": len(tmp_names), "registered": len(created), "failed": len(failed), "documents": created, "errors": failed, "duplicates": duplicates}


@router.post("/bulk-register/validate")
def validate_bulk_register(files: list[UploadFile] = File(...), db: Session = Depends(get_db), current_user: models.User = Depends(get_current_user)):
    """Validate uploaded files for bulk registration. Files are saved temporarily for inspection by the client if desired.
    This endpoint does NOT create Document records; it only validates files and stores them in a temporary location.
    """
    require_permission(current_user, "register_documents")
    os.makedirs(TEMP_UPLOAD_DIR, exist_ok=True)

    results = []
    total = 0
    valid_count = 0
    invalid_count = 0
    for idx, f in enumerate(files, start=1):
        total += 1
        filename = getattr(f, "filename", None) or ""
        content_type = getattr(f, "content_type", None)
        try:
            # read up to MAX_FILE_SIZE + 1 to detect oversize
            content = f.file.read(MAX_FILE_SIZE + 1)
            size = len(content)
            is_allowed, errors = _is_allowed_file(filename, content_type)
            if size == 0:
                errors.append("Empty file")
            if size > MAX_FILE_SIZE:
                errors.append("File exceeds maximum allowed size")
            valid = len(errors) == 0 and is_allowed
            if valid:
                valid_count += 1
                # save to temporary file for possible later confirm; name safely
                safe_name = f"tmp_{int(datetime.now(timezone.utc).timestamp())}_{secrets.token_hex(8)}_{os.path.basename(filename)}"
                tmp_path = os.path.join(TEMP_UPLOAD_DIR, safe_name)
                with open(tmp_path, "wb") as fh:
                    fh.write(content)
                results.append({"index": idx, "filename": filename, "valid": True, "size": size, "tmp_name": safe_name})
            else:
                invalid_count += 1
                results.append({"index": idx, "filename": filename, "valid": False, "errors": errors})
        except Exception as exc:
            invalid_count += 1
            results.append({"index": idx, "filename": filename or f"file_{idx}", "valid": False, "errors": [str(exc)]})
        finally:
            try:
                f.file.close()
            except Exception:
                pass

    return {"total_files": total, "valid_files": valid_count, "invalid_files": invalid_count, "files": results}


