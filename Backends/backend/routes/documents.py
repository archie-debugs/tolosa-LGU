@router.post("/{document_id:int}/handoffs")
def create_document_handoff(
    document_id: int,
    payload: schemas.DocumentHandoffCreate,
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    if getattr(current_user, "office_id", None) is None:
        raise HTTPException(status_code=403, detail="Office assignment required")
    if normalize_user_role(getattr(current_user, "role", None)) not in {"Employee", "Super Administrator"}:
        raise HTTPException(status_code=403, detail="Employee or Super Administrator access required")
    require_permission(current_user, "pass_office_documents")

    doc = db.query(models.Document).filter(models.Document.id == document_id).with_for_update().first()
    if not doc:
        raise HTTPException(status_code=404, detail="Document not found")
    if doc.archived:
        raise HTTPException(status_code=400, detail="Archived documents cannot be handed off")

    # Only the office currently holding the document may pass it on. Documents without a
    # recorded current office fall back to their office association.
    if doc.current_office_id is not None:
        holds_document = doc.current_office_id == current_user.office_id
    else:
        holds_document = db.query(models.DocumentOffice.id).filter(
            models.DocumentOffice.document_id == document_id,
            models.DocumentOffice.office_id == current_user.office_id,
        ).with_for_update().first() is not None
    if not holds_document:
        raise HTTPException(status_code=403, detail="This document is not currently held by your office")

    receiving_office = db.query(models.Office).filter(models.Office.id == payload.receiving_office_id).first()
    if receiving_office is None:
        raise HTTPException(status_code=404, detail="Receiving office not found")
    if not receiving_office.is_active:
        raise HTTPException(status_code=400, detail="Receiving office is inactive")
    if receiving_office.id == current_user.office_id:
        raise HTTPException(status_code=400, detail="Document cannot be handed off to the same office")

    pending = (
        db.query(models.DocumentHandoff)
        .filter(models.DocumentHandoff.document_id == document_id, models.DocumentHandoff.status == "Pending Receipt")
        .with_for_update()
        .first()
    )
    if pending is not None:
        raise HTTPException(status_code=409, detail="A pending receipt handoff already exists for this document")

    handoff = models.DocumentHandoff(
        document_id=document_id,
        sending_office_id=current_user.office_id,
        receiving_office_id=payload.receiving_office_id,
        sending_employee_id=current_user.id,
        sent_at=datetime.now(timezone.utc),
        status="Pending Receipt",
    )
    try:
        db.add(handoff)
        db.flush()
        db.refresh(handoff)
    except exc.IntegrityError as error:
        db.rollback()
        raise HTTPException(status_code=409, detail="A pending receipt handoff already exists for this document") from error

    result = _serialize_handoff(handoff)
    record_audit_log(
        db,
        actor=getattr(current_user, "username", "System"),
        action="DOCUMENT_HANDOFF_CREATED",
        target_type="document_handoff",
        target_id=str(handoff.id),
        details=f"Document {document_id} handed off from office {current_user.office_id} to office {payload.receiving_office_id}",
    )
    return result


def _close_pending_handoff(db: Session, handoff_id: int, current_user: models.User, status: str, reason: str | None) -> dict:
    """End a pending handoff without receipt. The sending office cancels it; the receiving office returns it.
    Custody only moves on receipt, so either way the sending office still holds the document."""
    if getattr(current_user, "office_id", None) is None:
        raise HTTPException(status_code=403, detail="Office assignment required")
    reason = (reason or "").strip() or None
    if status == "Returned" and reason is None:
        raise HTTPException(status_code=400, detail="Say why the document is being returned.")

    handoff = db.query(models.DocumentHandoff).filter(models.DocumentHandoff.id == handoff_id).with_for_update().first()
    if handoff is None:
        raise HTTPException(status_code=404, detail="Handoff not found")
    acting_office_id = handoff.sending_office_id if status == "Cancelled" else handoff.receiving_office_id
    if acting_office_id != current_user.office_id:
        if status == "Cancelled":
            raise HTTPException(status_code=403, detail="Only the office that sent this document can cancel the handoff")
        raise HTTPException(status_code=403, detail="Only the office this document was sent to can return it")
    if handoff.status != "Pending Receipt":
        raise HTTPException(status_code=409, detail=f"This handoff is already {handoff.status.lower()}")

    now = datetime.now(timezone.utc)
    handoff.status = status
    handoff.closed_at = now
    handoff.closed_by_user_id = current_user.id
    handoff.close_reason = reason
    handoff.updated_at = now
    db.flush()
    db.refresh(handoff)

    result = _serialize_handoff(handoff)
    verb = "cancelled by office" if status == "Cancelled" else "returned by office"
    record_audit_log(
        db,
        actor=getattr(current_user, "username", "System"),
        action="DOCUMENT_HANDOFF_CANCELLED" if status == "Cancelled" else "DOCUMENT_HANDOFF_RETURNED",
        target_type="document_handoff",
        target_id=str(handoff.id),
        details=f"Handoff of document {handoff.document_id} {verb} {current_user.office_id}" + (f": {reason}" if reason else ""),
    )
    return result


