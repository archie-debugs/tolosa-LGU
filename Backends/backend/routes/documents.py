@router.post("/bulk-register/validate")
def validate_bulk_register(files: list[UploadFile] = File(...), db: Session = Depends(get_db), current_user: models.User = Depends(get_current_user)):
    """Validate uploaded files for bulk registration. Files are saved temporarily for inspection by the client if desired.
    This endpoint does NOT create Document records; it only validates files and stores them in a temporary location.
    """
    require_permission(current_user, "register_documents")
    os.makedirs(TEMP_UPLOAD_DIR, exist_ok=True)

    results = []
    total = 0
    valid_count = 0
    invalid_count = 0
    for idx, f in enumerate(files, start=1):
        total += 1
        filename = getattr(f, "filename", None) or ""
        content_type = getattr(f, "content_type", None)
        try:
            # read up to MAX_FILE_SIZE + 1 to detect oversize
            content = f.file.read(MAX_FILE_SIZE + 1)
            size = len(content)
            is_allowed, errors = _is_allowed_file(filename, content_type)
            if size == 0:
                errors.append("Empty file")
            if size > MAX_FILE_SIZE:
                errors.append("File exceeds maximum allowed size")
            valid = len(errors) == 0 and is_allowed
            if valid:
                valid_count += 1
                # save to temporary file for possible later confirm; name safely
                safe_name = f"tmp_{int(datetime.now(timezone.utc).timestamp())}_{secrets.token_hex(8)}_{os.path.basename(filename)}"
                tmp_path = os.path.join(TEMP_UPLOAD_DIR, safe_name)
                with open(tmp_path, "wb") as fh:
                    fh.write(content)
                results.append({"index": idx, "filename": filename, "valid": True, "size": size, "tmp_name": safe_name})
            else:
                invalid_count += 1
                results.append({"index": idx, "filename": filename, "valid": False, "errors": errors})
        except Exception as exc:
            invalid_count += 1
            results.append({"index": idx, "filename": filename or f"file_{idx}", "valid": False, "errors": [str(exc)]})
        finally:
            try:
                f.file.close()
            except Exception:
                pass

    return {"total_files": total, "valid_files": valid_count, "invalid_files": invalid_count, "files": results}


