@router.put("/{document_id:int}", response_model=schemas.DocumentResponse)
def update_document(document_id: int, payload: schemas.DocumentUpdate, db: Session = Depends(get_db), current_user: models.User = Depends(get_current_user)):
    require_permission(current_user, "edit_documents")
    doc = db.query(models.Document).filter(models.Document.id == document_id).first()
    if not doc:
        raise HTTPException(status_code=404, detail="Document not found")

    if payload.tracking_number is not None and payload.tracking_number != doc.tracking_number:
        raise HTTPException(status_code=400, detail="Tracking numbers are generated automatically and cannot be changed.")

    data = payload.model_dump(exclude_unset=True)
    # The edit form sends None for a cleared field; required columns cannot be cleared.
    for field, label in (("title", "Title"), ("status", "Status"), ("priority", "Priority"), ("is_public", "Public visibility")):
        if field in data and (data[field] is None or (isinstance(data[field], str) and not data[field].strip())):
            raise HTTPException(status_code=400, detail=f"{label} is required.")
    if "series_year" in data:
        data["series_year"] = _require_legislative_year(data["series_year"])
    if "due_date" in data:
        data["due_date"] = _parse_due_date(data["due_date"])
    for field in SYSTEM_MANAGED_FIELDS:
        if field in data and data[field] != getattr(doc, field):
            raise HTTPException(status_code=400, detail="This field is managed by the system and cannot be edited.")
    for field, message in OFFICE_EDIT_REFUSALS.items():
        if field in data and not (data[field] and _same_name(data[field], getattr(doc, field))):
            raise HTTPException(status_code=400, detail=message)
    references = {}
    if "category" in data:
        references["category"] = _edited_reference(doc.category, doc.category_id, data["category"], "Category")
    if "document_type" in data:
        references["document_type"] = _edited_reference(doc.document_type, doc.document_type_id, data["document_type"], "Document type")
    previous_visibility = bool(doc.is_public)
    if "is_public" in data and data["is_public"] != previous_visibility:
        require_permission(current_user, "manage_public_visibility")
    # apply simple fields
    for field, value in data.items():
        if field in ("document_type", "category", "originating_office", "current_office", *SYSTEM_MANAGED_FIELDS):
            continue
        setattr(doc, field, value)
    # None clears both the name and its link.
    if "category" in references:
        doc.category, doc.category_id = references["category"]
    if "document_type" in references:
        doc.document_type, doc.document_type_id = references["document_type"]

    db.commit()
    db.refresh(doc)
    record_audit_log(
        db,
        actor=getattr(current_user, "username", "System"),
        action="DOCUMENT_UPDATED",
        target_type="document",
        target_id=str(doc.id),
        details=f"Updated document {doc.tracking_number}; fields={','.join(sorted(data.keys()))}",
    )
    if "is_public" in data and bool(doc.is_public) != previous_visibility:
        record_audit_log(
            db,
            actor=getattr(current_user, "username", "System"),
            action="DOCUMENT_VISIBILITY_CHANGED",
            target_type="document",
            target_id=str(doc.id),
            details=f"Set {doc.tracking_number} public visibility to {'public' if doc.is_public else 'private'}",
        )
    return _serialize_document(doc)


@router.post("/register", response_model=schemas.DocumentResponse)
def register_document(
    title: str = Form(...),
    document_number: Optional[str] = Form(None),
    series_year: Optional[int] = Form(None),
    description: Optional[str] = Form(None),
    category: Optional[str] = Form(None),
    document_type: Optional[str] = Form(None),
    office_id: Optional[int] = Form(None),
    current_office: Optional[str] = Form(None),
    assigned_to: Optional[str] = Form(None),
    action_required: Optional[str] = Form(None),
    author: Optional[str] = Form(None),
    priority: Optional[str] = Form("Medium"),
    due_date: Optional[str] = Form(None),
    allow_duplicate_number: bool = Form(False),
    tracking_number: Optional[str] = Form(None),
    stage: Optional[str] = Form(None),
    file: UploadFile | None = File(None),
    db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    require_permission(current_user, "register_documents")

    title = (title or "").strip()
    if not title:
        raise HTTPException(status_code=400, detail="Title is required")

    series_year = _require_legislative_year(series_year)

    if (tracking_number or "").strip():
        raise HTTPException(status_code=400, detail="Tracking numbers are generated automatically.")

    placement = _registration_placement(
        db, current_user, office_id=office_id, office_name=current_office, category=category, document_type=document_type,
        due_date=due_date,
    )

    inferred_number = _extract_legislative_number(file.filename if file and file.filename else title)
    typed_number = (document_number or "").strip() or None
    stage, document_number = registration_stage(
        placement["document_type"], stage,
        typed_number or (inferred_number or "").strip() or None, number_was_typed=typed_number is not None,
    )

    uploaded_content = None
    uploaded_checksum = None
    original_filename = os.path.basename(file.filename or "") if file is not None else None
    if file is not None:
        _, ext = os.path.splitext(original_filename.lower())
        if ext not in ALLOWED_EXTENSIONS:
            raise HTTPException(status_code=400, detail="Unsupported file type. Upload a PDF, DOC, or DOCX file.")
        uploaded_content = file.file.read(MAX_FILE_SIZE + 1)
        if len(uploaded_content) > MAX_FILE_SIZE:
            raise HTTPException(status_code=413, detail="File exceeds maximum allowed size")
        uploaded_checksum = hashlib.sha256(uploaded_content).hexdigest()
        duplicate_documents = _documents_with_checksum(db, uploaded_checksum)
        if duplicate_documents:
            raise HTTPException(status_code=409, detail=_duplicate_reason(duplicate_documents))

    if not allow_duplicate_number:
        type_name = placement["document_type"]
        same_number = _documents_with_number(db, type_name, document_number, series_year)
        if same_number:
            raise HTTPException(status_code=409, detail=_duplicate_number_detail(same_number))

    try:
        doc = _new_registered_document(
            db, current_user, placement,
            title=title, document_number=document_number, series_year=series_year, description=description,
            assigned_to=assigned_to, action_required=(action_required or "").strip() or None, author=author, priority=priority, stage=stage,
        )
    except ValueError as exc:
        raise HTTPException(status_code=409, detail=str(exc))

    if file is not None:
        try:
            os.makedirs(UPLOAD_DIR, exist_ok=True)
            content = uploaded_content or b""
            safe_name = f"{int(datetime.now(timezone.utc).timestamp())}_{secrets.token_hex(8)}_{original_filename}"
            dest_path = os.path.join(UPLOAD_DIR, safe_name)
            with open(dest_path, "wb") as fh:
                fh.write(content)
            doc.attachment_name = safe_name
            db.add(models.Attachment(
                document_id=doc.id,
                original_filename=original_filename,
                stored_path=dest_path,
                mime_type=file.content_type or mimetypes.guess_type(original_filename)[0],
                size=len(content),
                checksum=uploaded_checksum,
            ))
            db.commit()
        except Exception as exc:
            db.rollback()
            raise HTTPException(status_code=500, detail=f"Failed to save uploaded file: {exc}")

    db.refresh(doc)
    _record_registration(db, current_user, doc)
    db.refresh(doc)
    return _serialize_document(doc)


